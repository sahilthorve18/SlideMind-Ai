// Backward compatibility lookup with legacy alias support
export const getDesignSystemById = (id) => {
  if (!id) return DESIGN_SYSTEMS[0]
  const direct = DESIGN_SYSTEMS.find((ds) => ds.id === id)
  if (direct) return direct

  // Legacy fallback mapping
  const aliases = {
    swiss_minimal: 'swiss_bauhaus',
    startup_pitch: 'pitch_venture',
    financial_analyst: 'stripe_scale',
    brutalist: 'brutalist_raw',
    cybersecurity: 'cyber_terminal',
    futuristic_ai: 'cyber_terminal',
    japanese_minimalism: 'editorial_monocle',
    editorial_magazine: 'editorial_monocle',
    academic_research: 'editorial_monocle',
    architecture_portfolio: 'swiss_bauhaus',
    creative_agency: 'pitch_venture',
    education_modern: 'stripe_scale',
    documentary_storytelling: 'luxury_maison',
    luxury_brand: 'luxury_maison',
    deeptech_emerald: 'cyber_terminal',
    pitch_deck: 'pitch_venture',
  }
  const mappedId = aliases[id]
  return DESIGN_SYSTEMS.find((ds) => ds.id === mappedId) || DESIGN_SYSTEMS[0]
}

