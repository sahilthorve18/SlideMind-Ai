def get_design_system(theme_name: str | None) -> DesignSystem:
    """Resolve a design system by name or legacy theme alias, defaulting to swiss_minimal."""
    if not theme_name:
        return DESIGN_SYSTEMS["swiss_minimal"]
    key = theme_name.strip().lower().replace(" ", "_").replace("-", "_")
    if key in DESIGN_SYSTEMS:
        return DESIGN_SYSTEMS[key]
    if key in LEGACY_THEME_MAP:
        return DESIGN_SYSTEMS[LEGACY_THEME_MAP[key]]
    return DESIGN_SYSTEMS["swiss_minimal"]


def list_design_systems() -> List[Dict[str, Any]]:
    """Return serializable summary of all available design systems for UI selection."""
    return [
        {
            "id": ds.id,
            "name": ds.name,
            "description": ds.description,
            "category": ds.category,
            "dark_mode": ds.dark_mode,
            "background": ds.background_hex,
            "card_bg": ds.card_bg_hex,
            "title_color": ds.title_hex,
            "accent": ds.accent_hex,
            "border": ds.border_hex,
            "font_title": ds.font_title.split(",")[0].strip(),
            "font_body": ds.font_body.split(",")[0].strip(),
            "layout_style": ds.layout_style,
            "card_radius": ds.card_radius,
            "gradient": ds.gradient_accent,
        }
        for ds in DESIGN_SYSTEMS.values()
    ]


def to_legacy_theme_styles() -> Dict[str, Tuple[Tuple[float, float, float], Tuple[float, float, float], Tuple[float, float, float], str]]:
    """Generate THEME_STYLES dict matching the structure slides.py expects."""
    res = {}
    for ds_id, ds in DESIGN_SYSTEMS.items():
        res[ds_id] = (ds.background_rgb, ds.title_rgb, ds.body_rgb, ds.font_title.split(",")[0].strip())
    # Ensure legacy keys exist
    for legacy_key, target_id in LEGACY_THEME_MAP.items():
        if legacy_key not in res:
            res[legacy_key] = res[target_id]
    return res
